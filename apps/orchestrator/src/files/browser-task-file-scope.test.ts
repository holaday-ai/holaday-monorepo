import { rm } from 'node:fs/promises';
import { expect, it, vi } from 'vitest';
import { BrowserTaskFileReader } from '../agent/browser-tools/browser-task-file-reader.js';
import {
  BrowserTaskFiles,
  type ValidatedBrowserTaskFile,
} from '../agent/browser-tools/browser-task-files.js';
import { BrowserTaskTable } from '../agent/browser-tools/browser-task-table.js';
import { createBrowserTaskFileScope } from './browser-task-file-scope.js';
import { browserOutputFixture } from './testing/browser-output-fixture.js';

async function generatedFixture() {
  const f = await browserOutputFixture();
  const row = await f.service.storeOutput({
    userIdInternal: 7,
    userExternalId: 'usr_alice',
    taskIdInternal: 9,
    requireLiveTask: true,
    filename: 'analysis.csv',
    mimetype: 'text/csv',
    buffer: Buffer.from('metric,value\na,1\nb,2\n'),
  });
  const scope = createBrowserTaskFileScope({
    db: f.db,
    files: f.service,
    userId: 7,
    taskId: 'tsk_alice',
    origin: 'user',
    inputs: [],
  });
  const receipt = {
    fileId: row.externalId,
    filename: row.filename,
    size: row.sizeBytes,
    downloadUrl: `/api/files/${row.externalId}/download`,
  };
  return { ...f, row, scope, receipt };
}

it('reads and analyzes its proven generated CSV without granting upload authority', async () => {
  const f = await generatedFixture();
  try {
    await f.scope.admitGenerated(f.receipt);
    const reader = new BrowserTaskFileReader(f.scope);
    expect(await reader.read({ fileId: f.row.externalId })).toMatchObject({
      coverage: { complete: true },
      source: { kind: 'task_generated' },
      websiteExportScope: 'not_applicable',
    });
    expect(reader.coverageNote()).toContain('任务生成');
    const table = await new BrowserTaskTable(f.scope).run({
      fileId: f.row.externalId,
      mode: 'aggregate',
      metrics: [{ op: 'sum', column: 'B' }],
    });
    expect(table).toMatchObject({ complete: true, overall: [{ value: '3' }] });
    expect(f.scope.references()).toEqual([]);
    await expect(f.scope.resolve('tsk_alice', [f.row.externalId])).rejects.toThrow();
  } finally {
    await rm(f.root, { recursive: true, force: true });
  }
});

it.each(['other-task', 'unattached', 'owner', 'input', 'expired', 'filename', 'size', 'url'])(
  'refuses generated material without its exact live task/output receipt (%s)',
  async (reason) => {
    const f = await generatedFixture();
    try {
      const row = f.records.find((r) => r.externalId === f.row.externalId)!;
      if (reason === 'other-task') {
        f.taskRecords.push({
          id: 11,
          externalId: 'tsk_other_alice',
          userId: 7,
          origin: 'user',
          status: 'executing',
        });
        row.taskId = 11;
      }
      if (reason === 'unattached') row.taskId = null;
      if (reason === 'owner') row.userId = 8;
      if (reason === 'input') row.kind = 'input';
      if (reason === 'expired') row.expiresAt = new Date(Date.now() - 1);
      if (reason === 'filename') f.receipt.filename = 'other.csv';
      if (reason === 'size') f.receipt.size += 1;
      if (reason === 'url') f.receipt.downloadUrl = 'https://unapproved.example/file';
      await expect(f.scope.admitGenerated(f.receipt)).rejects.toThrow();
      await expect(f.scope.resolveReadable('tsk_alice', [f.row.externalId])).rejects.toThrow();
      expect(f.scope.references()).toEqual([]);
    } finally {
      await rm(f.root, { recursive: true, force: true });
    }
  },
);

it('does not admit generated bytes after account revocation during storage read', async () => {
  const f = await generatedFixture();
  try {
    const load = f.service.loadMany.bind(f.service);
    vi.spyOn(f.service, 'loadMany').mockImplementation(async (...args) => {
      const rows = await load(...args);
      f.faults.ownerStatus = 'closing';
      return rows;
    });
    await expect(f.scope.admitGenerated(f.receipt)).rejects.toThrow();
    expect(f.scope.references()).toEqual([]);
  } finally {
    vi.restoreAllMocks();
    await rm(f.root, { recursive: true, force: true });
  }
});

it('keeps the generated content immutable across reads and repeated receipts', async () => {
  const f = await generatedFixture();
  try {
    await f.scope.admitGenerated(f.receipt);
    const loaded = await f.service.loadMany([f.row.externalId], 7);
    vi.spyOn(f.service, 'loadMany').mockResolvedValue(
      loaded.map((file) => ({
        ...file,
        buffer: Buffer.from('metric,value\na,9\nb,9\n'),
      })),
    );
    await expect(f.scope.resolveReadable('tsk_alice', [f.row.externalId])).rejects.toThrow();
    await expect(f.scope.admitGenerated(f.receipt)).rejects.toThrow();
  } finally {
    vi.restoreAllMocks();
    await rm(f.root, { recursive: true, force: true });
  }
});

